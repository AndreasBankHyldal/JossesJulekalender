import { expect, test } from '@playwright/test'
import { adventDays } from '../../src/data/advent'
import { CALENDAR_YEAR } from '../../src/lib/calendar'
import { signIn } from './sign-in'

for (const reducedMotion of ['no-preference', 'reduce'] as const) {
  test(`December 8 directly reveals a rereadable walk and cafe invitation with ${reducedMotion} motion`, async ({ page }) => {
    const day = adventDays[7]
    const activity = day.activity
    if (!activity) throw new Error('December 8 must have a walk and cafe activity')
    await page.emulateMedia({ reducedMotion })
    await page.clock.install({ time: new Date(CALENDAR_YEAR, 11, 8, 12) })
    await page.goto('/')
    await signIn(page, 'josse')
    const door = page.getByRole('button', { name: '8. december, åbn din overraskelse', exact: true })
    await door.focus()
    await page.keyboard.press('Enter')
    const dialog = page.getByRole('dialog')
    const card = dialog.getByRole('region', { name: 'DAGENS AKTIVITET' })
    const close = dialog.getByRole('button', { name: 'Luk og vend tilbage til kalenderen' })
    const back = dialog.getByRole('button', { name: 'Tilbage til vores december' })
    await page.clock.fastForward(2_000)
    await expect(dialog.getByRole('heading', { name: 'En gåtur med dig', level: 2 })).toBeVisible()
    await expect(dialog.locator('#reveal-message')).toHaveText(day.message)
    await expect(card).toBeVisible()
    await expect(card.getByText(day.littleJoy, { exact: true })).toBeVisible()
    await expect(card.getByRole('listitem')).toHaveText(activity.essentials)
    await expect(card.getByText(activity.timing, { exact: true })).toBeVisible()
    await expect(card.locator('.activity-illustration')).toHaveAttribute('aria-hidden', 'true')
    await expect(card.getByRole('button')).toHaveCount(0)
    await expect(dialog.getByRole('button')).toHaveCount(2)
    await expect(dialog.locator('.little-joy')).toHaveCount(0)
    expect(await card.evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true)
    expect(await dialog.locator('.reveal-letter').evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true)
    const initialContent = await card.innerText()

    await expect(close).toBeFocused()
    await page.keyboard.press('Shift+Tab')
    await expect(back).toBeFocused()
    await expect(back).toBeInViewport()
    await page.keyboard.press('Tab')
    await expect(close).toBeFocused()
    await page.keyboard.press('Tab')
    await expect(back).toBeFocused()
    await page.keyboard.press('Escape')
    await expect(dialog).toHaveCount(0)
    const openedDoor = page.getByRole('button', { name: '8. december, åbnet, læs igen', exact: true })
    await expect(openedDoor).toBeFocused()
    await page.keyboard.press('Enter')
    await expect(card).toHaveText(initialContent, { useInnerText: true })
    await back.click()
    await page.clock.setFixedTime(new Date(CALENDAR_YEAR, 11, 12, 12))
    await page.reload()
    await signIn(page, 'josse')
    await openedDoor.click()
    await expect(card).toHaveText(initialContent, { useInnerText: true })
    await back.click()
    await expect(dialog).toHaveCount(0)
    await expect(page.getByText('1 af 24 små glæder', { exact: true })).toBeVisible()
  })
}

test('December 8 stays date-locked for Josse while admin can read the invitation early', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.clock.install({ time: new Date(CALENDAR_YEAR, 11, 7, 12) })
  await page.goto('/')
  await signIn(page, 'josse')
  const door = page.getByRole('button', { name: '8. december, låst indtil den 8. december', exact: true })
  await expect(door).toHaveAttribute('aria-disabled', 'true')
  await door.click({ force: true })
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByText(`Lidt tålmodighed, goffe. Låge 8 åbner den 8. december ${CALENDAR_YEAR}.`)).toBeVisible()
  await page.getByRole('button', { name: 'Log ud', exact: true }).click()
  await signIn(page, 'admin')
  await page.getByRole('button', { name: '8. december, åbn din overraskelse', exact: true }).click()
  await expect(page.getByRole('region', { name: 'DAGENS AKTIVITET' })).toContainText(adventDays[7].littleJoy)
})
